@router.message(Command("resorts"))
async def cmd_resorts(message: Message):
    """Показывает список курортов для страны."""
    text = message.text.strip()
    if len(text.split()) < 2:
        await message.answer(
            "Укажи страну после команды.\n"
            "Пример: <code>/resorts Египет</code>\n\n"
            "Доступные: Египет, Турция, ОАЭ, Вьетнам, Таиланд",
            parse_mode="HTML",
        )
        return

    _, country_name = text.split(maxsplit=1)
    country_name = country_name.strip()

    resorts = get_resorts_for_country(country_name)
    if not resorts:
        await message.answer(
            f"⚠️ Страна <b>{country_name}</b> пока не найдена.\n"
            f"Доступные: Египет, Турция, ОАЭ, Вьетнам, Таиланд",
            parse_mode="HTML",
        )
        return

    lines = [
        f"🏖 <b>Курорты {country_name}</b> ({len(resorts)} шт.)\n\n"
        f"<em>Выбери курорт и используй /tour для поиска тура или /compare для сравнения.</em>\n\n"
    ]
    for i, r in enumerate(resorts, 1):
        thesis = r.get("thesis", "")
        target = ", ".join(r.get("target", []))
        budget = r.get("budget_level", {})
        budget_str = " / ".join([f"{k}: {v:,}₽" for k, v in budget.items()]) if budget else "—"
        lines.append(
            f"{i}. <b>{r['name']}</b>\n"
            f"   {thesis}\n"
            f"   👥 {target}\n"
            f"   💰 {budget_str}\n"
        )

    await message.answer("\n".join(lines), parse_mode="HTML")
