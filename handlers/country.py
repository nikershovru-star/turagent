@router.message(Command("country"))
async def cmd_country(message: Message):
    """Показывает информацию по стране."""
    text = message.text.strip()
    # Спрашиваем страну, если не указано
    if len(text.split()) < 2:
        await message.answer(
            "Укажи страну после команды.\nПример: <code>/country Египет</code>\n\n"
            "Доступные страны: Египет, Турция, ОАЭ, Вьетнам, Таиланд",
            parse_mode="HTML",
        )
        return

    _, country_name = text.split(maxsplit=1)
    country_name = country_name.strip()

    if country_name not in COUNTRY_DATA:
        available = ", ".join(COUNTRY_DATA.keys())
        await message.answer(
            f"⚠️ Страна <b>{country_name}</b> пока не найдена.\n\n"
            f"Доступные страны: {available}",
            parse_mode="HTML",
        )
        return

    data = COUNTRY_DATA[country_name]
    response = (
        f"📌 <b>{country_name}</b>\n\n"
        f"{data['visa']}\n\n"
        f"{data['currency']}\n\n"
        f"{data['best_time']}\n\n"
        f"{data['airport_note']}\n\n"
        f"{data['pitfalls']}"
    )
    await message.answer(response, parse_mode="HTML")
