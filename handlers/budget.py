def classify_budget(amount: int) -> dict:
    """
    Классифицирует сумму по уровню.
    Возвращает уровень и диапазон.
    """
    if amount < 30000:
        level = "min"
    elif amount < 60000:
        level = "mid"
    elif amount < 100000:
        level = "max"
    else:
        level = "lux"
    return level


@router.message(Command("budget"))
async def cmd_budget(message: Message):
    """Классифицирует бюджет клиента."""
    text = message.text.strip()
    
    # Пробуем извлечь сумму из текста
    import re
    # Ищем число (может быть с пробелами, разделителями)
    numbers = re.findall(r'\d[\d\s]*\d|\d', text)
    if not numbers:
        await message.answer(
            "Укажи бюджет после команды.\n"
            "Пример: <code>/budget 70000</code>\n\n"
            "Ответит: уровень отдыха (мин/сред/макс/люкс), что можно, что не рекомендуется.",
            parse_mode="HTML",
        )
        return
    
    # Берём первое число, убираем пробелы
    raw_number = numbers[0].replace(" ", "")
    try:
        amount = int(raw_number)
    except ValueError:
        await message.answer(
            f"⚠️ Не удалось определить сумму из <code>{text}</code>.\n"
            f"Попробуй: <code>/budget 70000</code>",
            parse_mode="HTML",
        )
        return
    
    if amount <= 0:
        await message.answer(
            "⚠️ Бюджет должен быть больше 0.",
            parse_mode="HTML",
        )
        return
    
    level = classify_budget(amount)
    data = BUDGET_LEVELS[level]
    
    # Диапазон
    if level == "min":
        range_text = "до 30 000 ₽"
    elif level == "mid":
        range_text = "30 000 – 60 000 ₽"
    elif level == "max":
        range_text = "60 000 – 100 000 ₽"
    else:
        range_text = "от 100 000 ₽"
    
    response = (
        f"{data['label']}\n"
        f"💵 Бюджет: {amount:,} ₽ ({range_text})\n\n"
        f"{data['description']}\n\n"
        f"{data['what_possible']}\n\n"
        f"{data['what_not']}\n\n"
        f"📌 <b>Рекомендация:</b> подбирай отели и туры в этом диапазоне. "
        f"Если клиент хочет больше — можем предложить более дорогие варианты."
    )
    
    await message.answer(response, parse_mode="HTML")
